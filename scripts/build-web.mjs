// Builds the web bundle for the app (www/) and refreshes the website's public settings.
//   node scripts/build-web.mjs            → www/ for the app + assets/poy-config.js for the website
//   POY_ANDROID_STORE=amazon node ...     → same, for the Amazon Appstore build
// Reads values from the environment, or from a .env file in the repo root if present.
// Only PUBLIC values are written (Supabase URL + anon key, RevenueCat public SDK keys, store links).
// © 2026 Adam Kornreich / R.A. Consulting ❤ Pops & Pippy
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "www");

// Minimal .env reader (KEY=value, # comments). Real environment variables win.
if (existsSync(join(ROOT, ".env"))) {
  for (const line of readFileSync(join(ROOT, ".env"), "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
  }
}
const env = (k, d = "") => process.env[k] ?? d;

// APP mode: "cloud" (default) or "local" (test mode, no sign-in). Fail loudly on anything else,
// and never let a CI / store build (Codemagic sets CI=true) ship with test mode on.
const MODE = env("POY_APP_MODE", "cloud").trim().toLowerCase() || "cloud";
if (!["cloud", "local"].includes(MODE)) { console.error(`POY_APP_MODE must be "cloud" or "local", got "${MODE}"`); process.exit(1); }
if (MODE === "local" && (process.env.CI || process.env.CM_BUILD_ID)) { console.error("Refusing to build with POY_APP_MODE=local on CI: test mode must never reach the stores."); process.exit(1); }

const SKIP = new Set(["node_modules", "www", "android", "ios", "supabase", "scripts", "resources", ".git", ".github",
  "package.json", "package-lock.json", "capacitor.config.json", "codemagic.yaml", ".env", ".env.example", ".gitignore"]);
const isDoc = (n) => n.endsWith(".md");

function config({ app }) {
  const cfg = {
    mode: MODE,
    siteUrl: env("POY_SITE_URL", "https://thepiratesofybor.com"),
    appScheme: "com.raconsulting.piratesofybor",
    supabaseUrl: env("POY_SUPABASE_URL"),
    supabaseAnonKey: env("POY_SUPABASE_ANON_KEY"),
    supabaseJs: app ? "assets/vendor/supabase.js" : "https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.45.4/dist/umd/supabase.min.js",
    revenuecat: { apple: env("POY_REVENUECAT_APPLE_KEY"), google: env("POY_REVENUECAT_GOOGLE_KEY"), amazon: env("POY_REVENUECAT_AMAZON_KEY") },
    androidStore: env("POY_ANDROID_STORE", "google"),
    appleServiceId: env("POY_APPLE_SERVICE_ID", "com.raconsulting.piratesofybor.signin"),
    storeLinks: { apple: env("POY_LINK_APP_STORE"), google: env("POY_LINK_GOOGLE_PLAY"), amazon: env("POY_LINK_AMAZON"), samsung: env("POY_LINK_GALAXY") },
    signIn: { apple: true, google: true, facebook: env("POY_SIGNIN_FACEBOOK", "true") === "true", tiktok: false },
  };
  return `/* Pirates of Ybor public settings, generated by scripts/build-web.mjs. Public values only.
   © 2026 Adam Kornreich / R.A. Consulting ❤ Pops & Pippy */
window.POY_CONFIG = ${JSON.stringify(cfg, null, 2)};
`;
}

// 1. Website settings (committed; safe to publish).
writeFileSync(join(ROOT, "assets", "poy-config.js"), config({ app: false }));

// 2. App bundle.
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const name of readdirSync(ROOT)) {
  if (SKIP.has(name) || name.startsWith(".") || isDoc(name)) continue;
  cpSync(join(ROOT, name), join(OUT, name), { recursive: true });
}
writeFileSync(join(OUT, "assets", "poy-config.js"), config({ app: true }));

// Bundle supabase-js so sign-in doesn't depend on a CDN inside the app.
const sb = join(ROOT, "node_modules", "@supabase", "supabase-js", "dist", "umd", "supabase.js");
mkdirSync(join(OUT, "assets", "vendor"), { recursive: true });
if (existsSync(sb)) cpSync(sb, join(OUT, "assets", "vendor", "supabase.js"));
else {
  console.warn("! node_modules/@supabase/supabase-js not found; the app will load it from the CDN instead. Run npm install.");
  writeFileSync(join(OUT, "assets", "poy-config.js"), config({ app: false }));
}

let files = 0, bytes = 0;
(function walk(d) { for (const n of readdirSync(d)) { const p = join(d, n); const s = statSync(p); if (s.isDirectory()) walk(p); else { files++; bytes += s.size; } } })(OUT);
console.log(`www/ ready: ${files} files, ${(bytes / 1048576).toFixed(1)} MB, mode=${MODE}, store=${env("POY_ANDROID_STORE", "google")}, backend=${env("POY_SUPABASE_URL") ? "on" : "off (set POY_SUPABASE_URL)"}`);
